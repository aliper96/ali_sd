"""tile_split_stats.py — split-level statistics for the tile study (review 2026-10-05: the 3 detector
seeds of a split share generator and synthetic set, so the 15 (split, seed) pairs are not independent).
Unit = split (mean over its 3 seeds): 5 paired differences, Wilcoxon exact two-sided (minimum p = 0.0625),
sign count, mean and 95% CI of the split-level difference. Writes LaTeX macros.
  python prep/t23/tile_split_stats.py --results C:/Users/aliha/Desktop/PHD/t23_runs/live --out FirstPaper_renaming/generated/tile_split_numbers.tex
"""
import argparse, csv, json, os
import numpy as np
from scipy.stats import wilcoxon, t as tdist

ap = argparse.ArgumentParser()
ap.add_argument("--results", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()


def load(task, proto, sub="results"):
    """{split: {seed: row}}; --results is the live dir holding results/, results_textfix/, results_colorfix/"""
    d = {}
    for k in range(5):
        f = os.path.join(a.results, sub, f"split_{k}", task, f"{proto}.csv")
        if not os.path.exists(f):
            continue
        d[k] = {int(r["seed"]): r for r in csv.DictReader(open(f))}
    return d


METRIC = {"multiclass": "seg_mAP50_95", "binary": "mAP50_95"}
PROTOS = {"text": "results_textfix", "colour": "results_colorfix"}  # result dirs of the two carriers
mac, N = {}, {}
for task, met in METRIC.items():
    base = load(task, "D_S_AUG")
    for car, sub in PROTOS.items():
        nas = load(task, "NAS", sub)
        if not nas:
            continue
        ks = sorted(set(base) & set(nas))
        xb = np.array([np.mean([float(base[k][s][met]) for s in base[k]]) for k in ks])
        xn = np.array([np.mean([float(nas[k][s][met]) for s in nas[k]]) for k in ks])
        d = xn - xb
        p = float(wilcoxon(xn, xb).pvalue) if len(ks) > 1 else float("nan")
        ci = tdist.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
        tag = f"TileSplit{task.capitalize()}{car.capitalize()}"
        N[tag] = {"splits": len(ks), "base": xb.tolist(), "nas": xn.tolist(), "diff_mean": float(d.mean()),
                  "ci": [float(d.mean() - ci), float(d.mean() + ci)], "n_up": int((d > 0).sum()), "p_wilcoxon": p}
        mac[tag + "Diff"] = f"{d.mean():+.3f}"
        mac[tag + "CI"] = f"[{d.mean() - ci:+.3f}, {d.mean() + ci:+.3f}]"
        mac[tag + "Up"] = f"{int((d > 0).sum())}/{len(ks)}"
        mac[tag + "P"] = f"$p={p:.3f}$" if p == p else "--"
        print(f"{task:10s} {car:7s} NAS-D_S_AUG per split: {np.round(d, 3)}  mean {d.mean():+.3f} CI {mac[tag + 'CI']} up {mac[tag + 'Up']} p {p:.4f}")
os.makedirs(os.path.dirname(a.out), exist_ok=True)
with open(a.out, "w", encoding="utf-8") as f:
    f.write("% generated by prep/t23/tile_split_stats.py — do not edit\n")
    for k, v in mac.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
json.dump(N, open(a.out.replace(".tex", ".json"), "w"), indent=1)
print("wrote", a.out)
