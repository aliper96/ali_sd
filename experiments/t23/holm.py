"""holm.py — Holm-adjusted p-values for the pre-specified family of primary comparisons of the
per-category study (review 2026-10-05: many p-values without multiplicity correction).
Family (category-level Wilcoxon tests, the primary tests of Section 4.4): NAS colour vs real, NAS text vs
real, fidelity colour vs text, swap colour vs text, colour vs AD on the full fold, colour vs AD on the
unseen images. Writes \HolmXxx macros.
  python prep/t23/holm.py --numbers FirstPaper_renaming/generated/cat_numbers.json --out FirstPaper_renaming/generated/holm_numbers.tex
"""
import argparse, json
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--numbers", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()
N = json.load(open(a.numbers))["numbers"]
FAM = {"NasC": N["nas_c_vs_real"]["p_cat"], "NasT": N["nas_t_vs_real"]["p_cat"], "FidC": N["fid_c_vs_t"]["p_cat"],
       "SwapC": N["swap_c_vs_t"]["p_cat"], "AdFullC": N["ad"]["full_c_vs_ad"]["p_cat"], "AdCleanC": N["ad"]["clean_c_vs_ad"]["p_cat"]}
names, p = list(FAM), np.array(list(FAM.values()))
order = np.argsort(p); m = len(p); adj = np.empty(m)
running = 0.0
for rank, i in enumerate(order):  # Holm step-down
    running = max(running, (m - rank) * p[i]); adj[i] = min(1.0, running)


def fmt(x):
    return "$p<0.001$" if x < 0.001 else f"$p={x:.3f}$"


with open(a.out, "w", encoding="utf-8") as f:
    f.write("% generated by prep/t23/holm.py — do not edit\n")
    for n, pi, ai in zip(names, p, adj):
        f.write(f"\\newcommand{{\\Holm{n}}}{{{fmt(ai)}}}\n")
        print(f"{n:10s} raw {pi:.4f} -> Holm {ai:.4f}")
    f.write(f"\\newcommand{{\\HolmM}}{{{m}}}\n")
print("wrote", a.out)
