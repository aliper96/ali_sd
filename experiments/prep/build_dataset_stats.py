"""build_dataset_stats.py — MVTec-AD statistics table (tab:dataset_stats), counted from the data.

Columns: defect types; defect-free images of the official train/ split (used only as conditioning
inputs for textures and never for detector training); official test/ images (good and anomalous; the
anomalous ones are the only defective images MVTec-AD has, and they are re-split by us into a
generator-training fold and a held-out fold); ground-truth masks; and the sizes of our folds:
tile = 5 random splits of 60/24, other categories = one split (seed 0) read from the manifests.
  python prep/build_dataset_stats.py --mvtec mvtec_anomaly_detection --cat D:/ad/aliaug_cat --tile D:/DATASET/aliaug_splits --out FirstPaper_renaming/tab_dataset_stats.tex
"""
import argparse, glob, json, os

ap = argparse.ArgumentParser()
ap.add_argument("--mvtec", required=True)
ap.add_argument("--cat", required=True, help="per-category splits (<cat>/split_0/{train,test}_prompts.json)")
ap.add_argument("--tile", required=True, help="tile splits (split_k/{train,test}_prompts.json)")
ap.add_argument("--out", required=True)
a = ap.parse_args()

rows, tot = [], [0] * 7
cats = sorted(d for d in os.listdir(a.mvtec) if os.path.isdir(os.path.join(a.mvtec, d, "test")))
for c in cats:
    types = sorted(t for t in os.listdir(os.path.join(a.mvtec, c, "test")) if t != "good")
    n_tr_good = len(glob.glob(os.path.join(a.mvtec, c, "train", "good", "*.png")))
    n_te_good = len(glob.glob(os.path.join(a.mvtec, c, "test", "good", "*.png")))
    n_te_bad = sum(len(glob.glob(os.path.join(a.mvtec, c, "test", t, "*.png"))) for t in types)
    n_masks = sum(len(glob.glob(os.path.join(a.mvtec, c, "ground_truth", t, "*_mask.png"))) for t in types)
    if c == "tile":
        tr = sorted({len(json.load(open(f))) for f in glob.glob(os.path.join(a.tile, "split_*", "train_prompts.json"))})
        te = sorted({len(json.load(open(f))) for f in glob.glob(os.path.join(a.tile, "split_*", "test_prompts.json"))})
        fold = f"{'/'.join(map(str, tr))} / {'/'.join(map(str, te))}$^{{\\ast}}$"
        n_tr, n_te = tr[0], te[0]
    else:
        n_tr = len(json.load(open(os.path.join(a.cat, c, "split_0", "train_prompts.json"))))
        n_te = len(json.load(open(os.path.join(a.cat, c, "split_0", "test_prompts.json"))))
        fold = f"{n_tr} / {n_te}"
    rows.append((c.replace("_", "\\_"), len(types), n_tr_good, n_te_good, n_te_bad, n_masks, fold))
    for i, v in enumerate([len(types), n_tr_good, n_te_good, n_te_bad, n_masks, n_tr, n_te]):
        tot[i] += v

L = [r"""% Generated by prep/build_dataset_stats.py from the MVTec-AD release and the split manifests; do not edit.
\begin{table*}[ht]
\centering
\caption{MVTec-AD statistics per category, counted from the official release and from our split manifests.
\textbf{Good (train)}: defect-free images of the official \texttt{train} split, used only as conditioning inputs
for the texture categories; detectors are trained on defective images only. \textbf{Good (test)} and
\textbf{Defective (test)}: the official \texttt{test} split; its defective images, with their \textbf{GT masks},
are the only defective images of MVTec-AD, and we re-split them into a generator-training fold and a held-out
fold (\textbf{Train / held-out}: \textit{tile}, 5 random splits, Section~\ref{subsec:tile_protocol}; other
categories, one split, Section~\ref{subsec:mvtec_protocol}). The held-out fold is never used to train the
generator or the detector and is never augmented. $^{\ast}$per split.}
\label{tab:dataset_stats}
\renewcommand{\arraystretch}{1.05}
\setlength{\tabcolsep}{5pt}
\begin{small}
\begin{tabular}{@{}lcccccc@{}}
\toprule
\textbf{Category} & \textbf{\#Defect types} & \textbf{Good (train)} & \textbf{Good (test)} & \textbf{Defective (test)} & \textbf{GT masks} & \textbf{Train / held-out} \\
\midrule"""]
for r in rows:
    L.append(" & ".join(map(str, r)) + r" \\")
L.append(r"\midrule")
L.append(f"\\textbf{{Total}} & {tot[0]} & {tot[1]} & {tot[2]} & {tot[3]} & {tot[4]} & {tot[5]} / {tot[6]} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{small}", r"\end{table*}"]
open(a.out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(" | ".join(map(str, r)) for r in rows)); print("total", tot)
